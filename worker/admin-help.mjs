export function adminHelp(key) {
 const guide = guides[key];
 if (!guide) throw new Error('Unknown admin help section: '+key);
 const fields = guide.fields.map(([name,description]) => '<div><dt>'+escape(name)+'</dt><dd>'+escape(description)+'</dd></div>').join('');
 return '<details class="admin-help" data-admin-help="'+escape(key)+'"><summary>'+lamp+'<span>تعليمات '+escape(guide.title)+'</span><span class="admin-help-chevron" aria-hidden="true">⌄</span></summary><div class="admin-help-content"><p class="admin-help-intro">'+escape(guide.intro)+'</p><section><h3>الخطوات بالترتيب</h3><ol>'+guide.steps.map(step=>'<li>'+escape(step)+'</li>').join('')+'</ol></section><section><h3>معنى الخيارات والأزرار</h3><dl>'+fields+'</dl></section><section class="admin-help-notes"><h3>قبل أن تنتهي</h3><ul>'+guide.notes.map(note=>'<li>'+escape(note)+'</li>').join('')+'</ul></section></div></details>';
}
export function addAdminHelp(body) {
 body = body.replace('<div class="admin-tabs"',adminHelp('start')+'<div class="admin-tabs"');
 for (const key of Object.keys(guides).filter(key=>key!=='start')) {
  const pattern = new RegExp('(<section id="panel-'+key+'"[^>]*>)');
  if (!pattern.test(body)) throw new Error('Missing admin help target: '+key);
  body = body.replace(pattern, '$1'+adminHelp(key));
 }
 for (const [form,key] of [['product','products'],['category','categories'],['review','reviews'],['faq','faqs'],['post','posts'],['promo','cards']]) {
  const target = '<form id="'+form+'-form"><div class="editor-body">';
  if (!body.includes(target)) throw new Error('Missing admin help form: '+form);
  body = body.replace(target,target+adminHelp(key));
 }
 return body;
}
