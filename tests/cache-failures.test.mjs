import assert from 'node:assert/strict';
import {publicCatalog} from '../worker/public-cache.mjs';
import {publicMedia} from '../worker/media-cache.mjs';
let revision='one',loads=0,puts=0;
const catalog={products:[],presentation:{title:'current'}};
const env={DB:{prepare(){return {async first(){return {revision};}};}}};
const load=async()=>{loads++;return catalog;};
const origin='https://cache-test.example';
const broken={async match(){throw Error('offline');},async put(){throw Error('offline');}};
assert.deepEqual(await publicCatalog(env,origin,load,broken),catalog);
assert.equal(loads,1);
const corrupt={async match(){return new Response('invalid JSON');},async put(){puts++;}};
assert.deepEqual(await publicCatalog(env,origin,load,corrupt),catalog);
assert.equal(puts,1);
puts=0;
const empty={async match(){},async put(){puts++;}};
await publicCatalog(env,origin,async()=>{revision='two';return catalog;},empty);
assert.equal(puts,0,'concurrent write must not store a mixed snapshot');
assert.deepEqual(await publicCatalog({DB:{prepare(){throw Error('missing migration');}}},origin,load,empty),catalog);
const image=()=>new Response(new Uint8Array([1,2,3]),{headers:{etag:'"one"','content-type':'image/webp','cache-control':'private, max-age=86400'}});
const request=new Request(origin+'/media/test');
assert.deepEqual(new Uint8Array(await (await publicMedia(request,{},image,broken)).arrayBuffer()),new Uint8Array([1,2,3]));
puts=0;
const error=await publicMedia(request,{},()=>new Response('missing',{status:404,headers:{'cache-control':'private, no-store'}}),empty);
assert.equal(error.status,404);assert.equal(error.headers.get('cache-control'),'private, no-store');assert.equal(puts,0);
const hit={async match(){return image();}};
const head=await publicMedia(new Request(request,{method:'HEAD'}),{},()=>{throw Error('should hit');},hit);
assert.equal(await head.text(),'');assert.equal(head.headers.get('etag'),'"one"');
const conditional=await publicMedia(new Request(request,{headers:{'if-none-match':'W/"one"'}}),{},image,hit);
assert.equal(conditional.status,304);
console.log('PASS cache failures, corrupt entry, concurrent mutation, missing migration, error freshness, HEAD and ETag');
